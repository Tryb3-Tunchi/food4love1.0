// Equirectangular projection into a 360 x 180 box.
export function projectCentre(code: string): { x: number; y: number } | null {
  const centre = COUNTRY_CENTRES[code]
  if (!centre) return null
  return { x: centre[1] + 180, y: 90 - centre[0] }
}
